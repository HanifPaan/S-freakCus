#!/bin/bash
# exim_queue_guard.sh
#
# Exim spool guard: when the spool goes over a size or inode limit,
# removes queued mail older than MAX_AGE, in small batches.
#
# Project : https://github.com/HanifPaan/S-freakCus  (folder: exim-queue-guard)
# Settings: /etc/exim_queue_guard.conf   (never overwritten by updates)
#
# Usage:
#   exim_queue_guard.sh                 check the spool and clean up if needed (what cron runs)
#   exim_queue_guard.sh --apply         rewrite cron + logrotate from the conf file now
#   exim_queue_guard.sh --update        update to the latest release now
#   exim_queue_guard.sh --check-update  show installed and latest version
#   exim_queue_guard.sh --version       show installed version
#   exim_queue_guard.sh --auto-update   daily cron entry (does nothing when AUTO_UPDATE=0)
#
# Uninstall: /usr/local/bin/exim_queue_guard_uninstall.sh

VERSION="dev"
REPO="HanifPaan/S-freakCus"
SUBDIR="exim-queue-guard"
TAG_PREFIX="exim-queue-guard-v"
RAW_BASE="https://raw.githubusercontent.com/$REPO"
API_RELEASES="https://api.github.com/repos/$REPO/releases?per_page=100"

PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
CONF="/etc/exim_queue_guard.conf"
BIN="/usr/local/bin/exim_queue_guard.sh"
CRON="/etc/cron.d/exim_queue_guard"
ROTATE="/etc/logrotate.d/exim_queue_guard"
LOCK="/var/run/exim_queue_guard.lock"

# ---------- defaults (used when the conf file is missing a value) ----------
SPOOL="/var/spool/exim/input"
MAX_INODES=300000
MAX_SIZE_MB=3072
MAX_AGE=86400
BATCH_SIZE=250
BATCH_SLEEP=5
MAX_PER_RUN=5000
DRYRUN=0
SCHEDULE="0 * * * *"
AUTO_UPDATE=1
UPDATE_SCHEDULE="30 4 * * *"
LOG="/var/log/exim_queue_guard.log"
LOG_KEEP=2
# ---------------------------------------------------------------------------

log() { echo "$(date '+%F %T') $*" >> "$LOG"; }
die() { echo "ERROR: $*" >&2; log "ERROR: $*"; exit 1; }

usage() { sed -n '10,18p' "$BIN" 2>/dev/null | sed 's/^# \{0,1\}//'; }

load_conf() {
    [ -f "$CONF" ] || return 0
    if [ "$(stat -c %u "$CONF")" = "0" ] && [ -z "$(find "$CONF" -perm /022)" ]; then
        . "$CONF"
    else
        die "$CONF must be owned by root and not group/world-writable"
    fi
}

validate() {
    local v re='^[0-9*/,-]+( +[0-9*/,-]+){4}$'
    for v in MAX_INODES MAX_SIZE_MB MAX_AGE BATCH_SIZE BATCH_SLEEP MAX_PER_RUN DRYRUN AUTO_UPDATE LOG_KEEP; do
        case "${!v}" in
            ''|*[!0-9]*) die "$v='${!v}' in $CONF is not a number" ;;
        esac
    done
    [ "$BATCH_SIZE" -gt 0 ] || die "BATCH_SIZE must be 1 or more"
    [ "$LOG_KEEP"   -gt 0 ] || die "LOG_KEEP must be 1 or more"
    [[ $SCHEDULE        =~ $re ]] || die "SCHEDULE='$SCHEDULE' is not a valid 5-field cron time"
    [[ $UPDATE_SCHEDULE =~ $re ]] || die "UPDATE_SCHEDULE='$UPDATE_SCHEDULE' is not a valid 5-field cron time"
    case "$LOG" in /*) ;; *) die "LOG must be an absolute path" ;; esac
}

# Write a file only when its content changed (atomic replace).
write_if_changed() {   # $1 = path, $2 = content, $3 = mode
    local tmp
    [ "$(cat "$1" 2>/dev/null)" = "$2" ] && return 1
    tmp=$(mktemp "$(dirname "$1")/.eqg.XXXXXX") || return 1
    printf '%s\n' "$2" > "$tmp" && chmod "$3" "$tmp" && mv -f "$tmp" "$1"
}

# Cron + logrotate are built from the conf values, so SCHEDULE, AUTO_UPDATE,
# UPDATE_SCHEDULE and LOG_KEEP stay as the user set them.
apply() {
    local cron rot changed=""
    cron="# Managed by exim_queue_guard.sh - do not edit this file.
# Change SCHEDULE / AUTO_UPDATE / UPDATE_SCHEDULE in $CONF, then run: $BIN --apply
$SCHEDULE root nice -n 19 $BIN >/dev/null 2>&1"
    [ "$AUTO_UPDATE" -eq 1 ] && cron="$cron
$UPDATE_SCHEDULE root $BIN --auto-update >/dev/null 2>&1"

    rot="$LOG {
    monthly
    rotate $LOG_KEEP
    compress
    missingok
    notifempty
}"
    write_if_changed "$CRON"   "$cron" 644 && changed="$changed cron"
    write_if_changed "$ROTATE" "$rot"  644 && changed="$changed logrotate"
    [ -n "$changed" ] && log "APPLY: updated$changed (schedule='$SCHEDULE' auto_update=$AUTO_UPDATE log_keep=$LOG_KEEP)"
    return 0
}

fetch() {   # $1 = url, $2 = destination file
    if command -v curl >/dev/null 2>&1; then
        curl -fsSL --connect-timeout 15 --max-time 60 -o "$2" "$1"
    elif command -v wget >/dev/null 2>&1; then
        wget -q -T 60 -O "$2" "$1"
    else
        return 1
    fi
}

# Newest non-prerelease GitHub release whose tag starts with TAG_PREFIX.
latest_tag() {
    local tmp
    tmp=$(mktemp) || return 1
    if ! fetch "$API_RELEASES" "$tmp"; then rm -f "$tmp"; return 1; fi
    tr ',{}' '\n\n\n' < "$tmp" | awk -v p="$TAG_PREFIX" '
        /"tag_name"[ ]*:/            { t=$0; sub(/.*"tag_name"[ ]*:[ ]*"/,"",t); sub(/".*/,"",t) }
        /"prerelease"[ ]*:[ ]*false/ { if (index(t,p)==1) print t; t="" }
        /"prerelease"[ ]*:[ ]*true/  { t="" }' |
        grep -E "^${TAG_PREFIX}[0-9]+(\.[0-9]+)*$" | sort -V | tail -n1
    rm -f "$tmp"
}

update() {   # $1 = manual | auto
    local mode=$1 latest lv tmp
    latest=$(latest_tag)
    if [ -z "$latest" ]; then
        log "UPDATE: could not get the latest release from GitHub (offline, rate limit, or no release yet)"
        [ "$mode" = manual ] && echo "Could not get the latest release from GitHub (offline, rate limit, or no release yet)." >&2
        exit 1
    fi
    lv=${latest#"$TAG_PREFIX"}

    if [ "$lv" = "$VERSION" ]; then
        [ "$mode" = manual ] && echo "Already up to date (v$VERSION)."
        exit 0
    fi
    # Only move forward. A non-release install (dev / branch) always moves to the latest release.
    if [[ $VERSION =~ ^[0-9]+(\.[0-9]+)*$ ]] &&
       [ "$(printf '%s\n%s\n' "$VERSION" "$lv" | sort -V | tail -n1)" = "$VERSION" ]; then
        [ "$mode" = manual ] && echo "Installed v$VERSION is not older than the latest release v$lv. Nothing to do."
        exit 0
    fi

    tmp=$(mktemp -d /tmp/eqg-update.XXXXXX) || die "cannot create temp dir"
    if ! fetch "$RAW_BASE/$latest/$SUBDIR/setup.sh" "$tmp/setup.sh" || ! bash -n "$tmp/setup.sh" 2>/dev/null; then
        rm -rf "$tmp"
        log "UPDATE: failed to download a valid setup.sh for $latest"
        [ "$mode" = manual ] && echo "Failed to download a valid setup.sh for $latest." >&2
        exit 1
    fi
    [ "$mode" = manual ] && echo "Updating v$VERSION -> v$lv ..."
    EQG_TMP="$tmp" exec bash "$tmp/setup.sh" --update --ref "$latest"
}

cleanup() {
    apply   # keep cron/logrotate in sync with the conf file

    [ -d "$SPOOL" ] || die "$SPOOL not found"

    exec 9>"$LOCK"
    flock -n 9 || exit 0       # skip if a previous run is still going

    local inodes size_mb over="" ids count todo batches start done_n=0 took left i
    local -a id_list batch
    inodes=$(find "$SPOOL" 2>/dev/null | wc -l)
    size_mb=$(du -sm "$SPOOL" 2>/dev/null | awk '{print $1}')

    [ "$inodes"  -ge "$MAX_INODES"  ] && over="$over inodes=$inodes(>=$MAX_INODES)"
    [ "$size_mb" -ge "$MAX_SIZE_MB" ] && over="$over size=${size_mb}MB(>=${MAX_SIZE_MB}MB)"

    # Under both limits: nothing to do
    [ -z "$over" ] && exit 0

    log "LIMIT HIT:$over | queue=$(exim -bpc 2>/dev/null)"

    ids=$(exiqgrep -o "$MAX_AGE" -i 2>/dev/null)
    count=$(printf '%s\n' "$ids" | grep -c .)

    if [ "$count" -eq 0 ]; then
        log "No messages older than ${MAX_AGE}s. Nothing removed."
        exit 0
    fi

    todo=$count
    [ "$MAX_PER_RUN" -gt 0 ] && [ "$todo" -gt "$MAX_PER_RUN" ] && todo=$MAX_PER_RUN
    batches=$(( (todo + BATCH_SIZE - 1) / BATCH_SIZE ))

    if [ "$DRYRUN" -eq 1 ]; then
        log "DRYRUN: $count messages older than ${MAX_AGE}s; would remove $todo in $batches batches of $BATCH_SIZE (${BATCH_SLEEP}s pause)."
        exit 0
    fi

    mapfile -t id_list < <(printf '%s\n' "$ids" | grep . | head -n "$todo")

    start=$(date +%s)
    for (( i=0; i<${#id_list[@]}; i+=BATCH_SIZE )); do
        batch=( "${id_list[@]:i:BATCH_SIZE}" )
        exim -Mrm "${batch[@]}" >/dev/null 2>&1
        done_n=$(( done_n + ${#batch[@]} ))
        # pause between batches, not after the last one
        [ $(( i + BATCH_SIZE )) -lt ${#id_list[@]} ] && sleep "$BATCH_SLEEP"
    done
    took=$(( $(date +%s) - start ))

    left=$(( count - done_n ))
    log "Removed $done_n messages in $batches batches (${took}s), $left old left for next run. Now: inodes=$(find "$SPOOL" 2>/dev/null | wc -l) size=$(du -sm "$SPOOL" 2>/dev/null | awk '{print $1}')MB queue=$(exim -bpc 2>/dev/null)"
}

# ---------------- main ----------------
case "${1:-}" in
    --version|-v) echo "exim_queue_guard v$VERSION"; exit 0 ;;
    --help|-h)    usage; exit 0 ;;
esac

[ "$(id -u)" -eq 0 ] || { echo "Run as root." >&2; exit 1; }
load_conf
validate

case "${1:-}" in
    "")             cleanup ;;
    --apply)        apply; echo "Cron and logrotate now match $CONF:"; cat "$CRON" ;;
    --update)       update manual ;;
    --auto-update)  [ "$AUTO_UPDATE" -eq 1 ] || exit 0; update auto ;;
    --check-update)
        latest=$(latest_tag)
        echo "Installed : v$VERSION"
        if [ -n "$latest" ]; then echo "Latest    : v${latest#"$TAG_PREFIX"}"
        else echo "Latest    : unknown (could not reach GitHub, or no release yet)"; fi
        echo "Auto-update: $([ "$AUTO_UPDATE" -eq 1 ] && echo "on ($UPDATE_SCHEDULE)" || echo off)" ;;
    *)              usage; exit 1 ;;
esac
